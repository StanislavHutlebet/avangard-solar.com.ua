/**
 * Реальний IP відвідувача. Сайт не за Cloudflare і не за жодним проксі, що
 * сам проставляє/чистить X-Forwarded-For — тому довіряти цьому заголовку
 * не можна: клієнт може підставити в ньому будь-що, і тоді через нього
 * можна або підставити чужий IP під блокування, або обходити блокування
 * власного IP, щоразу міняючи значення заголовка. REMOTE_ADDR підробити
 * не можна, тому що це адреса реального TCP-з'єднання.
 */
function avangard_get_client_ip() {

	$ip = $_SERVER['REMOTE_ADDR'] ?? '';

	return filter_var( $ip, FILTER_VALIDATE_IP ) ? $ip : '';
}
